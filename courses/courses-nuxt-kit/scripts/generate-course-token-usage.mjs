import { readFile, readdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const projectRoot = process.cwd()
const libraryRoot = join(projectRoot, 'layers', 'courses', 'app')
const tokensPath = join(libraryRoot, 'assets', 'css', 'courses.css')
const outputPath = join(projectRoot, 'app', 'data', 'courseTokenUsage.generated.ts')

async function sourceFiles(directory) {
  const files = []
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) files.push(...await sourceFiles(path))
    else if (/\.(?:css|ts|vue)$/.test(entry.name)) files.push(path)
  }
  return files
}

const tokensSource = await readFile(tokensPath, 'utf8')
const rootMatch = tokensSource.match(/:root\s*\{([\s\S]*?)\n\}/)
if (!rootMatch) throw new Error('Courses :root token block was not found')

const definitions = new Map(
  [...rootMatch[1].matchAll(/--crs-([\w-]+)\s*:\s*([^;]+);/g)].map(match => [match[1], match[2]])
)

let librarySource = ''
for (const file of await sourceFiles(libraryRoot)) {
  let source = await readFile(file, 'utf8')
  if (file === tokensPath) source = source.replace(/:root\s*\{[\s\S]*?\n\}/, '')
  librarySource += `${source}\n`
}

const used = new Set([...librarySource.matchAll(/var\(\s*--crs-([\w-]+)/g)].map(match => match[1]))
let foundDependency = true
while (foundDependency) {
  foundDependency = false
  for (const token of [...used]) {
    for (const match of (definitions.get(token) || '').matchAll(/var\(\s*--crs-([\w-]+)/g)) {
      if (used.has(match[1])) continue
      used.add(match[1])
      foundDependency = true
    }
  }
}

const tokenNames = [...definitions.keys()]
const categories = {
  colors: tokenNames.filter(token => /^(?:chip-|blue-|black-|white|green|red|orange|yellow|violet|habr$|career$|qna$|twitter$|facebook$|vk$|telegram$|instagram$|ad-|overlay|placeholder|success-art|brand-hover|text-main$|links-main$|gradient-)/.test(token)),
  typography: tokenNames.filter(token => /^(?:font-|leading-|letter-)/.test(token)),
  radii: tokenNames.filter(token => token.startsWith('radius-')),
  spacing: tokenNames.filter(token => token.startsWith('space-')),
  layout: tokenNames.filter(token => ['container', 'content', 'gutter', 'unit'].includes(token))
}

const unused = Object.fromEntries(
  Object.entries(categories).map(([category, tokens]) => [category, tokens.filter(token => !used.has(token))])
)

const generated = `// Generated by scripts/generate-course-token-usage.mjs. Do not edit manually.\nexport const courseFoundationTokens = ${JSON.stringify(categories, null, 2)} as const\n\nexport const unusedCourseFoundationTokens = ${JSON.stringify(unused, null, 2)} as const\n`

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '')
  if (current !== generated) {
    console.error('Course token usage manifest is stale. Run: pnpm run generate:token-usage')
    process.exit(1)
  }
  console.log(`Course token usage check passed: ${used.size} referenced tokens; ${Object.values(unused).flat().length} unused foundation tokens.`)
} else {
  await writeFile(outputPath, generated)
  console.log(`Generated ${outputPath}`)
}
