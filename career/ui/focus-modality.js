/**
 * Модальность фокуса: отличает переход по Tab от фокуса указателем.
 *
 * Зачем. У текстовых полей `:focus-visible` по спецификации срабатывает всегда —
 * и по клику тоже, потому что поле принимает клавиатурный ввод независимо от
 * того, как в него попали. Поэтому CSS сам по себе не может показать кольцо
 * фокуса только при обходе с клавиатуры: для кнопок и вкладок `:focus-visible`
 * различает способ фокусировки, для input и textarea — нет.
 *
 * Что делает. Ставит на <html> атрибут data-focus-modality: `keyboard` после
 * Tab и `pointer` после нажатия указателем. `ui/state-contract.css` гасит по
 * нему внешнее кольцо у текстовых полей.
 *
 * Подключение необязательно. Без скрипта атрибута нет, правила гашения не
 * срабатывают и кольцо показывается всегда — то есть доступность не теряется,
 * а появляется лишний визуальный шум при клике. Правило выбрано так намеренно:
 * отсутствие скрипта не должно оставлять клавиатуру без видимого фокуса.
 *
 * Только Tab переводит режим в `keyboard`. Ввод текста и стрелки внутри поля
 * режим не меняют: стрелки двигают каретку, а не фокус. Обход стрелками внутри
 * составных виджетов — вкладок, меню, радиогрупп — здесь не нужен: там лежат
 * кнопки, у которых `:focus-visible` и так работает правильно, и правила
 * гашения на них не распространяются.
 */
(function () {
  var root = document.documentElement;

  function set(mode) {
    if (root.getAttribute('data-focus-modality') !== mode) {
      root.setAttribute('data-focus-modality', mode);
    }
  }

  addEventListener('keydown', function (event) {
    if (event.key === 'Tab' && !event.metaKey && !event.ctrlKey && !event.altKey) set('keyboard');
  }, true);

  addEventListener('pointerdown', function () { set('pointer'); }, true);
})();
